package("ltest-app")
    set_kind("binary")
    set_description("Discover and run test executables")
    set_license("GPL-3.0-only")
    set_sourcedir(path.join(os.scriptdir(), "../../../libs/ltest-app"))
    add_deps("lattice-test", "lattice-logger")
    on_install(function (package)
        local build_root = path.join(package:builddir(), "source", "ltest")
        os.tryrm(build_root)
        os.mkdir(build_root)
        os.cp("*", build_root)
        local script = io.readfile(path.join(build_root, "xmake.lua"))
        local stubs = import("stubs", {rootdir = path.join(package:scriptdir(), "../..")})
        io.writefile(path.join(build_root, "xmake.lua"),
            'set_languages("c++23")\nadd_rules("mode.debug", "mode.release")\n' .. stubs(package, {"lattice-test", "lattice-logger"}) .. script)
        os.cd(build_root)
        import("package.tools.xmake").install(package, {}, {target = "ltest"})
    end)
    on_test(function (package)
        os.vrunv(path.join(package:installdir("bin"), "ltest"), {"--help"})
    end)
